"""Regenerate common/on_actions/MFU_terrain_construction_on_actions.txt.

Run from anywhere after editing map/definition.csv or history/states:
    python tools/terrain_build_speed/generate.py
"""
import collections
import glob
import os
import re
import sys

MOD = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(MOD, "common", "on_actions", "MFU_terrain_construction_on_actions.txt")

TERRAIN_SPEED = {
    "plains": 0.0,
    "urban": 0.5,
    "forest": -0.2,
    "hills": -0.3,
    "marsh": -0.5,
    "desert": -0.7,
    "jungle": -0.9,
    "mountain": -1.2,
}
BUILDING_TABLES = {
    "rail_way": TERRAIN_SPEED,
    "infrastructure": TERRAIN_SPEED,
}
ALIASES = {"plain": "plains", "unknown": "plains", "desert_hills": "hills"}

MODIFIER = "MFU_terrain_construction"


def var_name(building):
    return f"MFU_terrain_{building}_speed"


def read_terrain():
    terrain = {}
    with open(os.path.join(MOD, "map", "definition.csv"), encoding="latin-1") as f:
        for line in f:
            p = line.strip().split(";")
            if len(p) >= 7 and p[0].isdigit():
                terrain[int(p[0])] = (p[4], ALIASES.get(p[6], p[6]))
    return terrain


def read_states():
    states = {}
    for path in glob.glob(os.path.join(MOD, "history", "states", "*.txt")):
        with open(path, encoding="utf-8-sig", errors="replace") as f:
            text = re.sub(r"#[^\n]*", "", f.read())
        sid = re.search(r"\bid\s*=\s*(\d+)", text)
        provs = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", text)
        if not sid or not provs:
            sys.exit(f"cannot parse id/provinces in {path}")
        sid = int(sid.group(1))
        if sid in states:
            sys.exit(f"duplicate state id {sid} in {path}")
        states[sid] = [int(x) for x in provs.group(1).split()]
    return states


def main():
    terrain = read_terrain()
    states = read_states()
    rows = []
    for sid in sorted(states):
        land = [terrain[p][1] for p in states[sid] if p in terrain and terrain[p][0] == "land"]
        missing = [p for p in states[sid] if p not in terrain]
        if missing:
            sys.exit(f"state {sid}: provinces not in definition.csv: {missing}")
        unknown = sorted({t for t in land if t not in TERRAIN_SPEED})
        if unknown:
            sys.exit(f"state {sid}: no speed value for terrain {unknown}")
        values = {}
        for building, table in BUILDING_TABLES.items():
            values[building] = (round(sum(table[t] for t in land) / len(land), 3) if land else 0.0) or 0.0
        rows.append((sid, values))

    lines = [
        "# Generated by tools/terrain_build_speed/generate.py - edit the tables there and re-run.",
        "on_actions = {",
        "\ton_startup = {",
        "\t\teffect = {",
    ]
    for sid, values in rows:
        sets = " ".join(f"set_variable = {{ {var_name(b)} = {v:g} }}" for b, v in values.items())
        lines.append(f"\t\t\t{sid} = {{ {sets} add_dynamic_modifier = {{ modifier = {MODIFIER} }} }}")
    lines += [
        "\t\t}",
        "\t}",
        "}",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))

    hist = collections.Counter(round(v["rail_way"], 1) for _, v in rows)
    print(f"wrote {len(rows)} states to {os.path.relpath(OUT, MOD)}")
    for b in sorted(hist):
        print(f"  {b:+.1f}: {hist[b]}")


if __name__ == "__main__":
    main()
