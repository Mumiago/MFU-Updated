r"""Regenerate the port-damage on_actions and scripted effects.

Outputs:
  common/on_actions/MFU_port_damage_on_actions.txt
  common/scripted_effects/MFU_port_damage_scripted_effects.txt

The engine has no province-control on_action, so once per day the first country to run
on_daily polls every port province's controller (global.MFU_pc_<province>). When a port
province changed hands between countries at war, that port loses DAMAGE_FRACTION of its
total level, but only if the port is at least MIN_LEVEL. Repeat captures of the same port, each within DECAY_WINDOW_DAYS of the
previous one, hit progressively less (DECAY per step), a stand-in for "fraction of healthy
levels" because script cannot read a province building's healthy level. Captures caused by
capitulation flips or ownership transfers (treaties, annexation, civil-war splits, releases)
are skipped through short-lived flags: a capitulated country's ports are exempt both as old
controller and as state owner. Scripted controller flips wrap the flip in
MFU_port_poll_state / MFU_port_record_state (state scope), as in 00_on_actions.txt.

Run after changing the constants below, history/states or the naval_base province_max.
From the mod root:
    python tools/port_damage/generate.py
"""
import glob
import os
import re
import sys

MOD = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_ON_ACTIONS = os.path.join(MOD, "common", "on_actions", "MFU_port_damage_on_actions.txt")
OUT_EFFECTS = os.path.join(MOD, "common", "scripted_effects", "MFU_port_damage_scripted_effects.txt")
BUILDINGS = os.path.join(MOD, "common", "buildings", "00_buildings.txt")

DAMAGE_FRACTION = 0.40
MIN_LEVEL = 6
DECAY = 0.65
DECAY_WINDOW_DAYS = 90
DECAY_STEPS = 3
SKIP_FLAG_DAYS = 2
DEBUG_LOG = True

CHUNKS = [8, 4, 2, 1, 0.5, 0.25, 0.1, 0.1, 0.05, 0.02, 0.02, 0.01]

AXIS = "OR = { tag = GER tag = ITA tag = JAP is_in_faction_with = GER is_in_faction_with = ITA is_in_faction_with = JAP }"
ALLIES = "OR = { tag = ENG tag = USA is_in_faction_with = ENG is_in_faction_with = USA }"

# province: [(old controller trigger, new controller trigger, "full" | "none"), ...]; other captures use the normal rule
SPECIAL_PORTS = {
    12725: [(ALLIES, AXIS, "full"), (AXIS, ALLIES, "none")],
}


def read_text(path):
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        return re.sub(r"#[^\n]*", "", f.read())


def naval_base_max_level():
    block = re.search(r"\bnaval_base\s*=\s*\{(.*?)\n\t\}", read_text(BUILDINGS), re.S)
    cap = re.search(r"province_max\s*=\s*(\d+)", block.group(1)) if block else None
    if not cap:
        sys.exit("cannot read naval_base province_max from 00_buildings.txt")
    return int(cap.group(1))


def read_ports():
    ports = {}
    for path in glob.glob(os.path.join(MOD, "history", "states", "*.txt")):
        text = read_text(path)
        sid = re.search(r"\bid\s*=\s*(\d+)", text)
        if not sid:
            sys.exit(f"cannot parse state id in {path}")
        provs = re.search(r"\bprovinces\s*=\s*\{([^}]*)\}", text)
        members = set(provs.group(1).split()) if provs else set()
        found = [int(p) for p, _ in re.findall(r"(\d+)\s*=\s*\{[^{}]*?naval_base\s*=\s*(\d+)", text)]
        stray = [p for p in found if str(p) not in members]
        if stray:
            sys.exit(f"{path}: naval_base provinces {stray} are not in the state's provinces list")
        if found:
            ports[int(sid.group(1))] = found
    return ports


def num(x):
    return f"{x:g}"


def level_ladder(top, trigger):
    lines = []
    for i, level in enumerate(range(top, MIN_LEVEL - 1, -1)):
        keyword = "if" if i == 0 else "else_if"
        lines.append(
            f"{keyword} = {{ limit = {{ {trigger(level - 1)} }} "
            f"set_temp_variable = {{ MFU_pd_level = {level} }} }}"
        )
    return lines


def build_effects(top):
    L = ["# Generated by tools/port_damage/generate.py - edit the constants there and re-run."]
    L += [
        "MFU_port_damage_apply = {",
        "\tset_temp_variable = { MFU_pd_amount = MFU_pd_level }",
        f"\tmultiply_temp_variable = {{ MFU_pd_amount = {num(DAMAGE_FRACTION)} }}",
        "\tmultiply_temp_variable = { MFU_pd_amount = MFU_pd_mult }",
    ]
    for chunk in CHUNKS:
        L.append(
            f"\tif = {{ limit = {{ check_variable = {{ MFU_pd_amount > {num(chunk - 0.001)} }} }} "
            f"damage_building = {{ type = naval_base province = var:MFU_pd_prov damage = {num(chunk)} }} "
            f"subtract_from_temp_variable = {{ MFU_pd_amount = {num(chunk)} }} }}"
        )
    L += ["}", ""]
    return L


def port_block(prov, top):
    L = [f"set_variable = {{ MFU_pd_prov = {prov} }}"]
    L += level_block(prov, top)
    rules = SPECIAL_PORTS.get(prov, [])
    if not rules:
        return L + normal_block(prov) + ["clear_variable = MFU_pd_prov"]
    for i, (old, new, action) in enumerate(rules):
        keyword = "if" if i == 0 else "else_if"
        body = []
        if action == "full":
            body.append(
                "if = { limit = { check_variable = { MFU_pd_level > 0 } } "
                f"damage_building = {{ type = naval_base province = var:MFU_pd_prov damage = {top} }} }}"
            )
        if DEBUG_LOG:
            body.append(f'log = "MFU port damage: port {prov} in [THIS.GetName], special rule {action}, level [?MFU_pd_level]"')
        L.append(
            f"{keyword} = {{ limit = {{ var:global.MFU_pd_old = {{ {old} }} var:global.MFU_pc_{prov} = {{ {new} }} }} "
            f"{' '.join(body)} }}"
        )
    L.append("else = {")
    L += ["\t" + line for line in normal_block(prov)]
    L += ["}", "clear_variable = MFU_pd_prov"]
    return L


def level_block(prov, top):
    L = ["set_temp_variable = { MFU_pd_level = 0 }"]
    L += level_ladder(
        top,
        lambda k: f"any_province_building_level = {{ province = {{ id = {prov} }} building = naval_base level > {k} }}",
    )
    return L


def normal_block(prov):
    L = ["set_temp_variable = { MFU_pd_mult = 1 }"]
    for n in range(DECAY_STEPS, 0, -1):
        keyword = "if" if n == DECAY_STEPS else "else_if"
        L.append(
            f"{keyword} = {{ limit = {{ has_state_flag = MFU_port_hit_{prov}_{n} }} "
            f"set_temp_variable = {{ MFU_pd_mult = {DECAY ** n:.4f} }} }}"
        )
    window = f"days = {DECAY_WINDOW_DAYS} value = 1"
    L += ["if = {", "\tlimit = { check_variable = { MFU_pd_level > 0 } }", "\tMFU_port_damage_apply = yes"]
    for n in range(DECAY_STEPS, 0, -1):
        keyword = "if" if n == DECAY_STEPS else "else_if"
        target = n if n == DECAY_STEPS else n + 1
        sets = " ".join(f"set_state_flag = {{ flag = MFU_port_hit_{prov}_{k} {window} }}" for k in range(1, target + 1))
        L.append(f"\t{keyword} = {{ limit = {{ has_state_flag = MFU_port_hit_{prov}_{n} }} {sets} }}")
    L += [f"\telse = {{ set_state_flag = {{ flag = MFU_port_hit_{prov}_1 {window} }} }}", "}"]
    if DEBUG_LOG:
        L.append(
            f'log = "MFU port damage: port {prov} in [THIS.GetName], level [?MFU_pd_level] '
            f'(0 = below {MIN_LEVEL}), factor [?MFU_pd_mult]"'
        )
    return L


def store(prov):
    return f"var:global.province_controllers^{prov} = {{ set_variable = {{ global.MFU_pc_{prov} = THIS }} }}"


def guarded_store(prov):
    return f"if = {{ limit = {{ check_variable = {{ global.province_controllers^{prov} > 0 }} }} {store(prov)} }}"


def build_state_polls(top, ports):
    L = []
    for sid, plist in sorted(ports.items()):
        L.append(f"MFU_port_poll_{sid} = {{")
        for prov in plist:
            var = f"global.MFU_pc_{prov}"
            L += [
                f"\tif = {{ limit = {{ NOT = {{ has_variable = {var} }} }} {guarded_store(prov)} }}",
                f"\telse_if = {{",
                f"\t\tlimit = {{ var:{var} = {{ NOT = {{ controls_province = {prov} }} }} }}",
                f"\t\tset_variable = {{ global.MFU_pd_old = {var} }}",
                f"\t\t{store(prov)}",
                "\t\tif = {",
                "\t\t\tlimit = {",
                f"\t\t\t\tvar:global.MFU_pd_old = {{ has_war_with = var:{var} NOT = {{ has_country_flag = MFU_port_damage_skip }} }}",
                f"\t\t\t\t{sid} = {{ NOT = {{ has_state_flag = MFU_port_damage_skip }} NOT = {{ owner = {{ has_country_flag = MFU_port_damage_skip }} }} }}",
                "\t\t\t}",
                f"\t\t\t{sid} = {{",
            ]
            L += ["\t\t\t\t" + line for line in port_block(prov, top)]
            L += ["\t\t\t}", "\t\t}", "\t}"]
        L += ["}", ""]
    return L


def build_poll(ports):
    L = ["MFU_port_poll = {"]
    L += [f"\tMFU_port_poll_{sid} = yes" for sid in sorted(ports)]
    L += ["}", ""]
    return L


def build_state_dispatch(ports):
    L = ["MFU_port_poll_state = {"]
    for i, sid in enumerate(sorted(ports)):
        keyword = "if" if i == 0 else "else_if"
        L.append(f"\t{keyword} = {{ limit = {{ state = {sid} }} MFU_port_poll_{sid} = yes }}")
    L += ["}", "", "MFU_port_record_state = {"]
    for i, (sid, plist) in enumerate(sorted(ports.items())):
        keyword = "if" if i == 0 else "else_if"
        L.append(f"\t{keyword} = {{ limit = {{ state = {sid} }} {' '.join(guarded_store(p) for p in plist)} }}")
    L += ["}", ""]
    return L


def build_on_actions():
    return [
        "# Generated by tools/port_damage/generate.py - edit the constants there and re-run.",
        "on_actions = {",
        "\ton_capitulation_immediate = { #ROOT is the capitulated country; runs before the engine flips its provinces",
        "\t\teffect = {",
        f"\t\t\tset_country_flag = {{ flag = MFU_port_damage_skip days = {SKIP_FLAG_DAYS} value = 1 }}",
        "\t\t}",
        "\t}",
        "\ton_state_owner_changed = { #ROOT is new owner #FROM is old owner #FROM.FROM is state",
        "\t\teffect = {",
        f"\t\t\tFROM.FROM = {{ set_state_flag = {{ flag = MFU_port_damage_skip days = {SKIP_FLAG_DAYS} value = 1 }} }}",
        "\t\t}",
        "\t}",
        "\ton_daily = { #fires per country; the first one each day runs the global port poll",
        "\t\teffect = {",
        "\t\t\tset_temp_variable = { MFU_pd_today = global.num_days }",
        "\t\t\tif = {",
        "\t\t\t\tlimit = { check_variable = { global.MFU_pd_day < MFU_pd_today } }",
        "\t\t\t\tset_variable = { global.MFU_pd_day = MFU_pd_today }",
        "\t\t\t\tMFU_port_poll = yes",
        "\t\t\t}",
        "\t\t}",
        "\t}",
        "}",
        "",
    ]


def write(path, lines):
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))


def main():
    top = naval_base_max_level()
    ports = read_ports()
    known = {p for plist in ports.values() for p in plist}
    missing = sorted(set(SPECIAL_PORTS) - known)
    if missing:
        sys.exit(f"SPECIAL_PORTS provinces without a history port: {missing}")
    write(OUT_ON_ACTIONS, build_on_actions())
    write(OUT_EFFECTS, build_effects(top) + build_state_polls(top, ports) + build_poll(ports) + build_state_dispatch(ports))
    multi = sum(len(p) for p in ports.values() if len(p) > 1)
    print(
        f"{sum(len(p) for p in ports.values())} ports in {len(ports)} states ({multi} in multi-port states); "
        f"{DAMAGE_FRACTION:.0%} of total level for ports of level {MIN_LEVEL}+, decay x{DECAY} within {DECAY_WINDOW_DAYS} days (max {DECAY_STEPS} steps)"
    )
    for path in (OUT_ON_ACTIONS, OUT_EFFECTS):
        print(f"wrote {os.path.relpath(path, MOD)} ({os.path.getsize(path) // 1024} KB)")


if __name__ == "__main__":
    main()
