r"""Regenerate the Afrika Korps data files (spirits, hidden desert techs, level/spawn effects, localisation).

Edit the tables below and re-run. From any folder:
    python -I "C:\Users\adamg\Documents\Paradox Interactive\Hearts of Iron IV\mod\MFU-Updated\tools\afrika_korps\generate.py"
From the mod root:
    python -I tools/afrika_korps/generate.py
Then verify with: python -I tools/afrika_korps/check.py
Design: docs/superpowers/specs/2026-11-12-afrika-korps-mechanic-design.md
"""
import os

MOD = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HEADER = "# Generated by tools/afrika_korps/generate.py - edit the tables there and re-run.\n"

SOV_LEVELS = range(0, 15)  # Soviet penalty in points; level 0 = spirit shell without a targeted modifier
DESERT_LEVELS = range(1, 11)  # desert/deep_desert attack in points; level 0 = no tech
# Every combat_width > 0 battalion carries category_front_line exactly once (checked in check.py), so one category
# covers all line battalions without stacking. HQ support units and light_armor_para carry it too (harmless).
DESERT_CATEGORIES = ["category_front_line"]
PICTURE = "GER_afrika_campaign"

# (key, state id, spawn province) in priority order; the trigger MFU_ak_city_<key> is defined in
# common/scripted_triggers/MFU_afrika_korps_scripted_triggers.txt
CITIES = [("tunis", 458, 11969), ("tripoli", 448, 1149), ("benghazi", 450, 11954), ("tobruk", 451, 13741)]

# Support companies = the existing German Panzer-Division template (history/units/GER_1936.txt), x = 0, y = 0..7
SUPPORT = ["artillery", "recon_ac", "mobile_engineer", "anti_tank", "maintenance_company",
           "logistics_company_mot", "anti_air_heavy_support", "signal_company"]

TEMPLATE_NAMES = {"medium": "Afrikakorps Panzer-Division", "light": "Afrikakorps leichte Panzer-Division"}
TANK_UNIT = {"medium": "medium_armor", "light": "light_armor"}
COUNT = {"medium": 3, "light": 4}

# (kind, trigger conditions, chassis id, variant name) - first match wins inside every city
VARIANTS = [
    ("medium", "MFU_ak_has_medium_tech = yes MFU_ak_has_medium_1940 = yes", "medium_tank_chassis_1940", "Panzer III Ausf.H"),
    ("medium", "MFU_ak_has_medium_tech = yes", "medium_tank_chassis_1946", "Panzer IV"),
    ("light", "MFU_ak_has_light_1940 = yes", "light_tank_chassis_1940", "Panzer 38(t)"),
    ("light", None, "light_tank_chassis_1936", "Panzer II Ausf.a"),
]


def regiments(kind, wide):
    tank = TANK_UNIT[kind]
    out = [(tank, x, y) for x in range(3) for y in range(3)]
    mot_rows = 4 if wide else 3
    out += [("motorized", x, y) for x in (3, 4) for y in range(mot_rows)]
    return out


def indent(lines, n):
    return [("\t" * n + ln) if ln else ln for ln in lines]


def chain(branches):
    """branches: list of (limit-or-None, body-lines) -> if / else_if / else lines (the last None becomes else)."""
    out = []
    for i, (limit, body) in enumerate(branches):
        if limit is None:
            out.append("else = {")
        else:
            out.append(("if = {" if i == 0 else "else_if = {"))
            out.append("\tlimit = { %s }" % limit)
        out += indent(body, 1)
        out.append("}")
    return out


def gen_ideas():
    lines = [HEADER.rstrip("\n"), "ideas = {", "\tcountry = {"]
    for n in SOV_LEVELS:
        lines += [
            "\t\tMFU_ak_spirit_%d = {" % n,
            "\t\t\tpicture = %s" % PICTURE,
            "\t\t\tallowed = {",
            "\t\t\t\talways = no",
            "\t\t\t}",
            "\t\t\tremoval_cost = -1",
        ]
        if n:
            lines += [
                "\t\t\ttargeted_modifier = {",
                "\t\t\t\ttag = SOV",
                "\t\t\t\tattack_bonus_against = -%.2f" % (n / 100.0),
                "\t\t\t\tdefense_bonus_against = -%.2f" % (n / 100.0),
                "\t\t\t}",
            ]
        lines += [
            "\t\t\tmodifier = {",
            "\t\t\t\tcustom_modifier_tooltip = MFU_ak_desert_tt",
            "\t\t\t\tcustom_modifier_tooltip = MFU_ak_decay_tt",
            "\t\t\t}",
            "\t\t}",
        ]
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


def gen_techs():
    lines = [HEADER.rstrip("\n"), "technologies = {"]
    for k in DESERT_LEVELS:
        lines += ["\tMFU_ak_desert_%d = {" % k, "\t\tresearch_cost = -1", "\t\tallow = {", "\t\t\talways = no", "\t\t}"]
        for cat in DESERT_CATEGORIES:
            lines.append("\t\t%s = {" % cat)
            for terrain in ("desert", "deep_desert"):
                lines += ["\t\t\t%s = {" % terrain, "\t\t\t\tattack = %.2f" % (k / 100.0), "\t\t\t}"]
            lines.append("\t\t}")
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_level_effects():
    ids = " ".join("MFU_ak_spirit_%d" % n for n in SOV_LEVELS)
    techs0 = ["MFU_ak_desert_%d = 0" % k for k in DESERT_LEVELS]
    lines = [HEADER.rstrip("\n")]
    lines += ["# Country scope. Reads MFU_ak_sov: removes every spirit level, then adds the exact one.",
              "MFU_ak_set_sov_idea = {", "\tremove_ideas = { %s }" % ids]
    lines += indent(chain([("check_variable = { MFU_ak_sov = %d }" % n, ["add_ideas = MFU_ak_spirit_%d" % n])
                           for n in SOV_LEVELS]), 1)
    lines += ["}", ""]
    lines += ["# Country scope. Reads MFU_ak_desert: zeroes every desert tech, then switches on the exact one.",
              "MFU_ak_set_desert_tech = {", "\tset_technology = {"]
    lines += ["\t\t" + t for t in techs0] + ["\t\tpopup = no", "\t}"]
    for k in DESERT_LEVELS:
        lines += ["\tif = {", "\t\tlimit = { check_variable = { MFU_ak_desert = %d } }" % k,
                  "\t\tset_technology = { MFU_ak_desert_%d = 1 popup = no }" % k, "\t}"]
    lines += ["}", ""]
    lines += ["# Country scope. Removes the whole spirit (every level and every desert tech).",
              "MFU_ak_clear_spirit = {", "\tremove_ideas = { %s }" % ids, "\tset_technology = {"]
    lines += ["\t\t" + t for t in techs0] + ["\t\tpopup = no", "\t}", "}"]
    return "\n".join(lines) + "\n"


def template_block(kind, wide):
    lines = ["division_template = {", '\tname = "%s"' % TEMPLATE_NAMES[kind], "\tdivision_names_group = GER_Arm_01",
             "\tpriority = 2", "\tregiments = {"]
    lines += ["\t\t%s = { x = %d y = %d }" % r for r in regiments(kind, wide)]
    lines += ["\t}", "\tsupport = {"]
    lines += ["\t\t%s = { x = 0 y = %d }" % (s, i) for i, s in enumerate(SUPPORT)]
    lines += ["\t}", "}"]
    return lines


def create_unit_block(state, province, kind, chassis, variant):
    division = ('division_template = \\"%s\\" start_experience_factor = 0.5 start_equipment_factor = 1 '
                'force_equipment_variants = { %s = { owner = \\"GER\\" version_name = \\"%s\\" } }'
                % (TEMPLATE_NAMES[kind], chassis, variant))
    return ["%d = {" % state, "\tcreate_unit = {", '\t\tdivision = "%s"' % division, "\t\towner = GER",
            "\t\tprioritize_location = %d" % province, "\t\tcount = %d" % COUNT[kind], "\t}", "}"]


def gen_spawn_effects():
    lines = [HEADER.rstrip("\n")]
    lines += ["# GER scope. Creates the one template this press needs (medium vs light, width tech or not).",
              "MFU_ak_create_template = {", "\thidden_effect = {"]
    tpl = chain([
        ("MFU_ak_has_medium_tech = yes MFU_ak_has_width_tech = yes", template_block("medium", True)),
        ("MFU_ak_has_medium_tech = yes", template_block("medium", False)),
        ("MFU_ak_has_width_tech = yes", template_block("light", True)),
        (None, template_block("light", False)),
    ])
    lines += indent(tpl, 2) + ["\t}", "}", ""]
    lines += ["# GER scope. Spawns the divisions in the first usable city (Tunis > Tripoli > Benghazi > Tobruk).",
              "MFU_ak_spawn_divisions = {", "\tMFU_ak_create_template = yes", "\thidden_effect = {"]
    city_branches = []
    for key, state, province in CITIES:
        variant_branches = [(cond, create_unit_block(state, province, kind, chassis, variant))
                            for kind, cond, chassis, variant in VARIANTS]
        city_branches.append(("MFU_ak_city_%s = yes" % key, chain(variant_branches)))
    lines += indent(chain(city_branches), 2) + ["\t}", "}"]
    return "\n".join(lines) + "\n"


